"""Sum, multiply, subtract, divide and power two values."""

__all__ = ["sum", "multiply", "subtract", "divide", "power"]


def sum(a, b):
    """Return a + b."""
    return a + b


def multiply(a, b):
    """Return a * b."""
    return a * b


def subtract(a, b):
    """Return a - b."""
    return a - b


def divide(a, b):
    """Return a / b."""
    return a / b


def power(a, b):
    """Return a ** b."""
    return a ** b
